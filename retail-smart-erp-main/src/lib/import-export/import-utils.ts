import type { EntityConfig, EntityFieldConfig, ImportMode } from './entity-config'
import { getImportFields, stockColumnKey, isStockColumnKey, stockColumnField, CLEAR_TOKEN } from './entity-config'
import Papa from 'papaparse'

export interface ImportError {
  row: number
  column: string
  message: string
  value: unknown
}

export interface ImportWarning {
  row: number
  column: string
  message: string
}

export interface ParsedRow {
  rowIndex: number
  /** Converted values for non-blank cells only. `null` = explicit clear (__CLEAR__). */
  data: Record<string, unknown>
  /** Original cell values keyed by file header (used for the errors CSV). */
  raw?: Record<string, string>
  /** Required fields that were blank (only an error once the row turns out to be an insert). */
  missingRequired?: string[]
  errors: ImportError[]
  warnings: ImportWarning[]
}

export interface ValidationResult {
  validRows: ParsedRow[]
  invalidRows: ParsedRow[]
  errors: ImportError[]
  warnings: ImportWarning[]
  totalRows: number
  validCount: number
  errorCount: number
  columns: string[]
}

// Parse CSV string into raw rows using papaparse for robust parsing
export function parseCsv(csvString: string): Record<string, string>[] {
  const result = Papa.parse(csvString, {
    header: true,
    skipEmptyLines: true,
    transformHeader: (header: string) => header.trim(),
    transform: (value: string) => value.trim(),
  })

  const rows = result.data as Record<string, string>[]
  // Drop the template's instruction row (row 2) — only when every cell looks like an instruction
  if (rows.length > 0 && isInstructionRow(Object.values(rows[0]))) rows.shift()

  if (result.errors.length > 0) {
    console.warn('CSV parsing warnings:', result.errors)
  }

  return rows
}

const INSTRUCTION_TOKEN = /^(yes\/no|yyyy-mm-dd( hh:mm:ss)?|number|integer|required|unique|enter \w+|string|decimal|boolean|date|datetime|enum|lookup|[^|]+( \| [^|]+)+)$/i

/**
 * True for the instruction row generated by our templates (e.g. "Required, Unique",
 * "Number", "Yes/No"). Real data rows are never dropped: every non-empty cell
 * must consist solely of instruction tokens.
 */
export function isInstructionRow(cells: unknown[]): boolean {
  const values = cells.map(c => String(c ?? '').trim()).filter(Boolean)
  if (values.length === 0) return false
  return values.every(v => v.split(/,\s*/).every(tok => INSTRUCTION_TOKEN.test(tok.trim())))
}

// Parse XLSX buffer into raw rows using SheetJS (supports both .xls and .xlsx)
export async function parseXlsx(buffer: ArrayBuffer): Promise<Record<string, string>[]> {
  const XLSX = await import('xlsx')

  // Read workbook from buffer
  const workbook = XLSX.read(buffer, { type: 'array' })

  // We only process the first worksheet
  const sheetName = workbook.SheetNames[0]
  if (!sheetName) return []

  const worksheet = workbook.Sheets[sheetName]

  // Convert to array of arrays to handle headers and skipping manually
  const jsonData = XLSX.utils.sheet_to_json(worksheet, {
    header: 1,
    blankrows: false,
    defval: ''
  }) as unknown[][]

  if (!jsonData || jsonData.length === 0) return []

  const rows: Record<string, string>[] = []
  let headers: string[] = []

  // Process rows
  for (let i = 0; i < jsonData.length; i++) {
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const row = jsonData[i] as any[]
    const rowIndex = i + 1

    // First row contains headers
    if (rowIndex === 1) {
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      headers = row.map((val: any) => {
        let strVal = String(val || '').trim()
        // Remove required marker
        strVal = strVal.replace(/\s*\*$/, '')
        return strVal
      })
      continue
    }

    // Skip the template instruction row (row 2) — only when it is clearly instructions
    if (rowIndex === 2 && isInstructionRow(row)) continue

    // Skip empty rows
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const hasData = row.some((val: any) => val !== null && val !== undefined && String(val).trim() !== '')
    if (!hasData) continue

    // Build record from row values
    const record: Record<string, string> = {}

    // Safety check: ensure we don't access out of bounds if row has fewer cells than headers
    // But also row might have more cells (ignore extra)
    headers.forEach((header, colIndex) => {
      if (header) {
        const val = row[colIndex]
        let strVal = ''
        if (val instanceof Date) {
          strVal = val.toISOString().split('T')[0]
        } else if (val !== null && val !== undefined) {
          strVal = String(val).trim()
        }
        record[header] = strVal
      }
    })

    rows.push(record)

    // Limit processing
    if (rows.length >= 50000) {
      console.warn('Excel file contains more than 50,000 rows. Processing limited to first 50,000 rows.')
      break
    }
  }

  return rows
}

// Map column headers (label) to field keys.
// `stock:<WAREHOUSE_CODE>` headers map to the dynamic key `stock:<CODE>` (items only).
export function mapColumns(
  rawHeaders: string[],
  config: EntityConfig,
  businessType?: string
): Record<string, string> {
  const importFields = getImportFields(config, businessType)
  const mapping: Record<string, string> = {}

  for (const header of rawHeaders) {
    const normalized = header.trim().replace(/\s*\*$/, '') // Remove required marker

    if (config.name === 'items') {
      const stockKey = stockColumnKey(normalized)
      if (stockKey) {
        mapping[header] = stockKey
        continue
      }
    }

    // Try exact label match
    const exactMatch = importFields.find(f =>
      f.label.toLowerCase() === normalized.toLowerCase()
    )
    if (exactMatch) {
      mapping[header] = exactMatch.key
      continue
    }

    // Try key match
    const keyMatch = importFields.find(f =>
      f.key.toLowerCase() === normalized.toLowerCase()
    )
    if (keyMatch) {
      mapping[header] = keyMatch.key
      continue
    }

    // Fuzzy: remove spaces, dashes, underscores
    const clean = normalized.toLowerCase().replace(/[\s\-_]/g, '')
    const fuzzyMatch = importFields.find(f => {
      const cleanLabel = f.label.toLowerCase().replace(/[\s\-_]/g, '')
      const cleanKey = f.key.toLowerCase().replace(/[\s\-_]/g, '')
      return cleanLabel === clean || cleanKey === clean
    })
    if (fuzzyMatch) {
      mapping[header] = fuzzyMatch.key
    }
  }

  return mapping
}

/** Import fields plus any dynamic `stock:<CODE>` keys used by the mapping. */
export function getMappedImportFields(
  config: EntityConfig,
  columnMapping: Record<string, string>,
  businessType?: string,
): EntityFieldConfig[] {
  const fields = getImportFields(config, businessType)
  if (config.name !== 'items') return fields
  const dynamic = Array.from(new Set(Object.values(columnMapping).filter(k => k && isStockColumnKey(k))))
    .map(k => stockColumnField(canonStockKey(k)))
  return [...fields, ...dynamic]
}

function canonStockKey(key: string): string {
  return stockColumnKey(key) || key
}

/** Fill field defaults for keys that are absent (used for inserts only). */
export function applyDefaults(data: Record<string, unknown>, fields: EntityFieldConfig[]): Record<string, unknown> {
  const out: Record<string, unknown> = { ...data }
  for (const f of fields) {
    if (out[f.key] !== undefined && out[f.key] !== null) continue
    if (f.defaultValue === undefined) continue
    out[f.key] = convertValue(f, f.defaultValue).value
  }
  return out
}

function convertValue(field: EntityFieldConfig, transformedValue: string): { value?: unknown; error?: string } {
  switch (field.type) {
    case 'number': {
      const cleaned = transformedValue.replace(/,/g, '')
      const num = Number(cleaned)
      if (!Number.isFinite(num) || !Number.isInteger(num)) return { error: 'Must be a whole number' }
      return { value: num }
    }
    case 'decimal': {
      const cleaned = transformedValue.replace(/,/g, '')
      const num = Number(cleaned)
      if (cleaned === '' || !Number.isFinite(num)) return { error: 'Must be a number' }
      return { value: String(num) }
    }
    case 'boolean': {
      const lower = transformedValue.toLowerCase()
      if (['yes', 'true', '1', 'y'].includes(lower)) return { value: true }
      if (['no', 'false', '0', 'n'].includes(lower)) return { value: false }
      return { error: 'Must be Yes or No' }
    }
    case 'date': {
      if (!/^\d{4}-\d{2}-\d{2}$/.test(transformedValue)) return { error: 'Must be in YYYY-MM-DD format' }
      const d = new Date(transformedValue)
      if (isNaN(d.getTime())) return { error: 'Invalid date' }
      return { value: transformedValue }
    }
    case 'enum': {
      if (field.enumValues && !field.enumValues.includes(transformedValue)) {
        return { error: `Must be one of: ${field.enumValues.join(', ')}` }
      }
      return { value: transformedValue }
    }
    default:
      return { value: transformedValue }
  }
}

/**
 * Normalise + type-check rows (pure, no DB). Blank cells are left out of `data`
 * (blank = keep existing value on update); defaults are applied only when a row
 * is inserted. `__CLEAR__` sets a field to null in update/upsert mode.
 */
export function validateRows(
  rawRows: Record<string, string>[],
  config: EntityConfig,
  columnMapping: Record<string, string>,
  mode: ImportMode,
  businessType?: string
): ValidationResult {
  const importFields = getMappedImportFields(config, columnMapping, businessType)

  const validRows: ParsedRow[] = []
  const invalidRows: ParsedRow[] = []
  const allErrors: ImportError[] = []
  const allWarnings: ImportWarning[] = []
  const columns = Object.values(columnMapping)

  const MAX_ROWS = 30000
  const rowsToProcess = rawRows.slice(0, MAX_ROWS)

  if (rawRows.length > MAX_ROWS) {
    allWarnings.push({
      row: 0,
      column: '',
      message: `File contains ${rawRows.length} rows. Only the first ${MAX_ROWS} will be processed.`,
    })
  }

  for (let i = 0; i < rowsToProcess.length; i++) {
    const rawRow = rowsToProcess[i]
    const rowIndex = i + 1 // 1-indexed for user display
    const errors: ImportError[] = []
    const warnings: ImportWarning[] = []
    const missingRequired: string[] = []
    const cells: Record<string, string> = {}
    const data: Record<string, unknown> = {}

    // Map raw data using column mapping
    for (const [header, value] of Object.entries(rawRow)) {
      const mapped = columnMapping[header]
      if (!mapped) continue
      const fieldKey = isStockColumnKey(mapped) ? canonStockKey(mapped) : mapped
      cells[fieldKey] = value === undefined || value === null ? '' : String(value)
    }

    for (const field of importFields) {
      const strValue = (cells[field.key] ?? '').trim()

      let transformedValue: string = strValue
      if (field.transform === 'lowercase') transformedValue = strValue.toLowerCase()
      if (field.transform === 'uppercase') transformedValue = strValue.toUpperCase()

      if (strValue === CLEAR_TOKEN) {
        if (mode === 'insert') {
          if (field.required) missingRequired.push(field.label)
          continue
        }
        if (field.required) {
          errors.push({ row: rowIndex, column: field.label, message: `${field.label} cannot be cleared`, value: strValue })
        } else {
          data[field.key] = null
        }
        continue
      }

      if (!transformedValue) {
        if (field.required) missingRequired.push(field.label)
        continue
      }

      const converted = convertValue(field, transformedValue)
      if (converted.error) {
        errors.push({ row: rowIndex, column: field.label, message: converted.error, value: strValue })
      } else {
        data[field.key] = converted.value
      }
    }

    if (mode === 'insert') {
      for (const label of missingRequired) {
        errors.push({ row: rowIndex, column: label, message: `${label} is required`, value: '' })
      }
    }

    const parsed: ParsedRow = { rowIndex, data, raw: { ...rawRow }, missingRequired, errors, warnings }

    if (errors.length > 0) {
      invalidRows.push(parsed)
      allErrors.push(...errors)
    } else {
      validRows.push(parsed)
    }
    allWarnings.push(...warnings)
  }

  return {
    validRows,
    invalidRows,
    errors: allErrors,
    warnings: allWarnings,
    totalRows: rowsToProcess.length,
    validCount: validRows.length,
    errorCount: invalidRows.length,
    columns,
  }
}
